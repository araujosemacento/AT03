package main

func somar(valorUm float64, valorDois float64) float64 {
	return valorUm + valorDois
}
func subtrair(valorUm float64, valorDois float64) float64 {
	return valorUm - valorDois
}
func multiplicar(valorUm float64, valorDois float64) float64 {
	return valorUm * valorDois
}
func dividir(valorUm float64, valorDois float64) float64 {
	return valorUm / valorDois
}
